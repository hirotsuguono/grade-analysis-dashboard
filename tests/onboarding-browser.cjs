'use strict';
// End-to-end onboarding uses generated workbooks and synthetic names only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright-core');
const XLSX = require('../src/files/vendor/xlsx.full.min.js');
const app = path.resolve(process.env.DASHBOARD_ROOT || path.join(__dirname, '..', 'src'));
const output = path.resolve(process.env.QA_OUTPUT || path.join(__dirname, '..', 'test-results', 'onboarding'));
const checks = [], errors = [], external = [], dialogs = [];
const check = name => { checks.push(name); console.log('PASS ' + name); };
const rowsOf = (wb, sheet) => XLSX.utils.sheet_to_json(wb.Sheets[sheet], { header: 1, defval: '', blankrows: true });
const buffer = wb => Buffer.from(XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }));
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  try {
    const context = await browser.newContext({ acceptDownloads: true, offline: true, reducedMotion: 'reduce' });
    const page = await context.newPage();
    let acceptConfirm = true;
    page.on('dialog', async d => { dialogs.push(d.message()); if (d.type() === 'confirm' && !acceptConfirm) await d.dismiss(); else await d.accept(); });
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    page.on('requestfailed', r => errors.push(r.url()));
    page.on('request', r => { if (!/^(file:|data:|blob:)/.test(r.url())) external.push(r.url()); });
    const url = pathToFileURL(path.join(app, 'Index.html')).href;
    await page.goto(url);
    assert.ok(await page.locator('#newBtnEmpty').isVisible());
    assert.ok(await page.locator('#openBtnEmpty').isVisible());
    assert.ok(await page.locator('#demoBtn').isVisible());
    check('初回登録・JSON再開・サンプルの3入口');
    const download = async selector => {
      const event = page.waitForEvent('download');
      await page.locator(selector).click();
      const result = await event;
      const saved = path.join(output, result.suggestedFilename());
      await result.saveAs(saved);
      return saved;
    };
    const upload = async (selector, wb) => {
      await page.locator(selector).setInputFiles({ name: 'synthetic-workbook.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: buffer(wb) });
      // FileReader is asynchronous; wait for an import outcome, not a fixed sleep.
    };
    const importInitial = async wb => {
      await upload('#initialXlsxInput', wb);
      await page.waitForFunction(() => !document.getElementById('initialPreview').hidden);
    };
    const snapshot = () => page.evaluate(() => JSON.stringify(data));
    await page.locator('#newBtnEmpty').click();
    const initialPath = await download('#initialTemplateBtn');
    const blank = XLSX.read(fs.readFileSync(initialPath), { type: 'buffer' });
    assert.equal(blank.SheetNames[0], '初回登録');
    assert.ok(rowsOf(blank, '初回登録').slice(3).flat().every(v => v === ''));
    await importInitial(blank);
    assert.match(await page.locator('#initialPreview').textContent(), /名簿がありません/);
    assert.equal(await page.evaluate(() => data), null);
    check('発行した初回Excelの空入力・例シートを登録しない');
    const roster = [ [1, 'A', 1, '架空 同名', ''], [2, 'A', 1, '架空 同名', ''], [2, 'A', 2, '架空 あおい', ''], [2, 'A', 3, '架空 みどり', ''] ];
    function initial(scoreMode = false, duplicate = false) {
      const wb = XLSX.read(fs.readFileSync(initialPath), { type: 'buffer' });
      const rows = rowsOf(wb, '初回登録').slice(0, 3);
      rows[0][1] = '架空の初回操作';
      rows[1][1] = scoreMode ? '初回合計点' : '';
      rows[1][7] = 2; rows[1][9] = '2026-04-20';
      const entries = roster.map(row => row.slice());
      if (scoreMode) [entries[0][4], entries[1][4], entries[2][4], entries[3][4]] = [82, 0, '', '欠'];
      if (duplicate) entries[1] = entries[0].slice();
      wb.Sheets['初回登録'] = XLSX.utils.aoa_to_sheet(rows.concat(entries));
      return wb;
    }
    await page.locator('#setupCancelBtn').click();
    await page.locator('#newBtnEmpty').click();
    await importInitial(initial(false, true));
    assert.match(await page.locator('#initialPreview').textContent(), /重複/);
    assert.ok(await page.locator('#initialApplyBtn').isHidden());
    assert.equal(await page.evaluate(() => data), null);
    check('初回名簿の組番号重複を拒否し未登録を維持');
    await page.locator('#setupCancelBtn').click();
    await page.locator('#newBtnEmpty').click();
    await importInitial(initial());
    assert.match(await page.locator('#initialPreview').textContent(), /名簿だけ/);
    assert.match(await page.locator('#initialPreview').textContent(), /同姓同名/);
    assert.deepEqual(await page.locator('#initialPreview thead th').allTextContents(), ['学年', 'クラス', '出席番号', '氏名']);
    assert.deepEqual(await page.locator('#initialPreview tbody tr').first().locator('td').allTextContents(), ['1', 'A', '1', '架空 同名']);
    assert.equal(await page.evaluate(() => data), null);
    await page.screenshot({ path: path.join(output, 'initial-preview.png'), fullPage: true });
    await page.setViewportSize({ width: 320, height: 800 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.ok(await page.locator('#setupDialog').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await page.locator('#initialApplyBtn').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'initial-preview-mobile.png'), fullPage: true });
    await page.locator('#initialApplyBtn').click();
    const rosterData = JSON.parse(await snapshot());
    assert.equal(rosterData.students.length, 4);
    assert.ok(await page.locator('#sampleAssociationNote').isHidden());
    assert.equal(new Set(rosterData.students.map(s => s.id)).size, 4);
    assert.deepEqual(rosterData.students.slice(0, 2).map(s => s.className), ['1年A組', '2年A組']);
    assert.deepEqual(rosterData.tests, []); assert.deepEqual(rosterData.scores, []);
    assert.equal(await page.evaluate(() => dirty), true);
    assert.ok(await page.locator('#prepareTestTemplateBtn').isEnabled());
    check('プレビュー後の名簿のみ登録・同姓同名の別ID・架空テストなし');
    await page.screenshot({ path: path.join(output, 'roster-preparation.png'), fullPage: true });
    for (const width of [320, 390, 768, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    }
    check('名簿のみ画面の320/390/768/1280px表示');
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.locator('[data-tab="list"]').click();
    await page.locator('#listGrade').selectOption('1');
    assert.equal(await page.locator('.list-table tbody tr').count(), 1);
    await page.locator('#listGrade').selectOption('2');
    assert.equal(await page.locator('.list-table tbody tr').count(), 3);
    await page.locator('#listGrade').selectOption('all');
    check('別列から登録した学年で一覧を正しく絞り込む');
    const registered = await snapshot();
    for (const oldFormat of [false, true]) {
      await page.locator('#startFirstHeader').click();
      const invalidInitial = initial();
      const invalidRows = rowsOf(invalidInitial, '初回登録');
      if (oldFormat) {
        invalidRows[2] = ['クラス', '出席番号', '氏名', '合計点（任意）'];
        invalidRows.splice(3, invalidRows.length - 3, ['1年A組', 1, '架空 同名', '']);
      } else invalidRows[3][0] = 4;
      invalidInitial.Sheets['初回登録'] = XLSX.utils.aoa_to_sheet(invalidRows);
      await upload('#initialXlsxInput', invalidInitial);
      await page.waitForFunction(message => {
        const preview = document.getElementById('initialPreview');
        return !preview.hidden && preview.classList.contains('is-error') && preview.textContent.includes(message);
      }, oldFormat ? '最新版' : '名簿の学年');
      assert.match(await page.locator('#initialPreview').textContent(), oldFormat ? /最新版/ : /名簿の学年/);
      assert.ok(await page.locator('#initialApplyBtn').isHidden());
      assert.equal(await snapshot(), registered);
      await page.locator('#setupCancelBtn').click();
    }
    check('不正な学年・旧形式の初回Excelを拒否し登録済み名簿を保持');
    await page.locator('#startFirstHeader').click();
    await importInitial(initial(true));
    const before = await snapshot();
    acceptConfirm = false;
    await page.locator('#initialApplyBtn').click();
    assert.equal(await snapshot(), before);
    assert.ok(await page.locator('#setupDialog').isVisible());
    check('既存データ置換の確認を取消すると全データ保持');
    acceptConfirm = true;
    await page.locator('#initialApplyBtn').click();
    const first = JSON.parse(await snapshot());
    assert.equal(first.tests.length, 1); assert.equal(first.scores.length, 3);
    assert.equal(first.scores.find(r => r.studentId === first.students[1].id).total, 0);
    assert.ok(!first.scores.some(r => r.studentId === first.students[2].id));
    assert.ok(first.scores.find(r => r.studentId === first.students[3].id).absent);
    check('初回名簿と合計点を一度に登録・空欄/0点/欠席の区別');
    const metricPath = await download('#prepareMetricTemplateBtn');
    let wb = XLSX.read(fs.readFileSync(metricPath), { type: 'buffer' });
    let mr = rowsOf(wb, '指標');
    assert.deepEqual(mr.slice(2).map(r => r[5]), first.students.slice().sort((a,b) => a.className.localeCompare(b.className,'ja') || Number(a.number)-Number(b.number)).map(s => s.id));
    assert.ok(mr.slice(2).every(r => r[1] && r[2] && r[5]));
    const firstMetricId = mr[2][5], secondMetricId = mr[3][5];
    mr[1][3] = '架空の学習時間'; mr[2][3] = 25; mr[3][3] = 0;
    wb.Sheets['指標'] = XLSX.utils.aoa_to_sheet(mr);
    wb.SheetNames = ['記入例', '書き方', '指標'];
    await upload('#metricXlsxInput', wb);
    await page.waitForFunction(() => data.metrics.length === 1);
    let metric = await page.evaluate(() => data.metrics[0]);
    assert.equal(metric.values[firstMetricId], 25); assert.equal(metric.values[secondMetricId], 0);
    assert.equal(Object.keys(metric.values).length, 2);
    check('名簿・ID入りアンケートExcelの発行と取込・シート順変更・0の保持');
    mr[2][3] = ''; mr[3][3] = 3;
    wb.Sheets['指標'] = XLSX.utils.aoa_to_sheet(mr);
    await upload('#metricXlsxInput', wb);
    await page.waitForFunction(id => data.metrics[0].values[id] === 3, secondMetricId);
    assert.equal(await page.evaluate(id => data.metrics[0].values[id], firstMetricId), 25);
    check('追加指標の空欄で既存値を消さない');
    const rejectMetric = async (rows, pattern) => {
      const original = await snapshot(), n = dialogs.length;
      wb.Sheets['指標'] = XLSX.utils.aoa_to_sheet(rows);
      await upload('#metricXlsxInput', wb);
      await page.waitForFunction(() => document.getElementById('metricXlsxInput').value === '');
      await page.waitForEvent('dialog', { timeout: 2000 }).catch(() => {});
      assert.ok(dialogs.length > n); assert.match(dialogs.at(-1), pattern);
      assert.equal(await snapshot(), original);
    };
    const duplicate = mr.map(r => r.slice()); duplicate.push(duplicate[2].slice());
    await rejectMetric(duplicate, /重複/);
    const unknown = mr.map(r => r.slice()); unknown[2][5] = 'synthetic-unknown-id';
    await rejectMetric(unknown, /ID|未登録|一致/);
    const invalid = mr.map(r => r.slice()); invalid[2][3] = '数値ではない';
    await rejectMetric(invalid, /数字/);
    check('指標の重複・未照合・不正値は全件無変更');
    const testPath = await download('#prepareTestTemplateBtn');
    const twb = XLSX.read(fs.readFileSync(testPath), { type: 'buffer' });
    const sheet = twb.SheetNames[0], tr = rowsOf(twb, sheet);
    assert.deepEqual(tr[8].slice(0, 5), ['生徒ID', '学年', 'クラス', '出席番号', '氏名']);
    assert.equal(tr.slice(9).filter(r => r[4]).length, 4);
    const laterId = tr[9][0];
    tr[0][1] = '架空の追加テスト'; tr[1][1] = '英語'; tr[2][1] = 30;
    tr[3][1] = 2; tr[4][1] = '2026-05-20';
    tr[9][5] = 4; tr[9][6] = 5; tr[9][7] = 6;
    twb.Sheets[sheet] = XLSX.utils.aoa_to_sheet(tr);
    await upload('#testXlsxInput', twb);
    await page.waitForFunction(() => data.tests.length === 2);
    assert.equal(await page.evaluate(id => data.scores.find(r => r.studentId === id && r.testId === data.tests[1].id).total, laterId), 15);
    assert.deepEqual(await page.evaluate(id => data.scores.filter(r => r.testId === id), first.tests[0].id), first.scores);
    check('名簿・ID入り追加テストExcelの発行と取込・名簿の再入力不要');
    const state = await snapshot();
    const saved = await download('#saveBtn');
    assert.equal(JSON.stringify(JSON.parse(fs.readFileSync(saved))), state);
    await page.reload();
    const chooser = page.waitForEvent('filechooser');
    await page.locator('#openBtnEmpty').click();
    await (await chooser).setFiles(saved);
    await page.waitForFunction(() => data?.tests.length === 2);
    assert.equal(await snapshot(), state);
    assert.equal(await page.evaluate(() => dirty), false);
    check('同じJSONを保存して再開・生徒ID/テスト/指標の完全保持');
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    check('file://完全オフライン・JavaScript/読込エラーなし・外部通信なし');
    fs.writeFileSync(path.join(output, 'onboarding-results.json'), JSON.stringify({ checks, errors, external, browser: await browser.version() }, null, 2) + '\n');
    console.log(checks.length + ' checks passed.');
    await context.close();
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
