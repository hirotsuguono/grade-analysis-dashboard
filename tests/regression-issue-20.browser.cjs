'use strict';
const assert = require('node:assert/strict');
module.exports = async (page, fixture) => {
  await page.evaluate(value=>{applyJsonText(JSON.stringify(value),'fictional-karte.json',null);ui.trendSelected=new Set([data.students[0].id]);renderTrend();window.printRequested=false;},fixture);
  const before=await page.evaluate(()=>JSON.stringify(data));
  await page.locator('[data-tab="trend"]').click();
  await page.locator('#printKarteBtn').click();
  for(const key of ['basic','history','rate','average','trend','domain','memo']) await page.locator(`[data-karte="${key}"]`).uncheck();
  assert.deepEqual(await page.locator('#kartePreview th').allTextContents(),['テスト','得点']);
  assert.equal(await page.locator('#kartePreview img').count(),0);
  assert.ok(!(await page.locator('#kartePreview').textContent()).includes('面談メモ'));
  await page.locator('[data-karte="records"]').uncheck();
  assert.equal(await page.locator('#kartePreview').innerHTML(),'');
  assert.ok(await page.locator('#kartePrintBtn').isDisabled());
  await page.locator('[data-karte="basic"]').check();
  await page.locator('[data-karte="memo"]').check();
  await page.setViewportSize({width:320,height:800});
  assert.ok(await page.locator('#karteDialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>window.printRequested),false);
  await page.locator('#printKarteBtn').click();
  assert.ok(await page.locator('[data-karte="memo"]').isChecked());
  const preview=await page.locator('#kartePreview').innerHTML();
  await page.locator('#kartePrintBtn').click();
  await page.waitForFunction(()=>window.printRequested);
  assert.equal(await page.locator('#printArea').innerHTML(),preview);
  assert.equal(await page.evaluate(()=>JSON.stringify(data)),before);
  await page.setViewportSize({width:1280,height:900});
};
